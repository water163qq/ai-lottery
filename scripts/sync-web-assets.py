#!/usr/bin/env python3
"""Sync the web front-end into the Android WebView assets.

The web app uses ES modules, which do not load over file:// in old WebViews.
This script concatenates js/data.js, js/engine.js and js/app.js into a single
classic script and rewrites the index.html script tag accordingly.
"""

import pathlib
import re
import shutil
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "lottery-ai"
DST = ROOT / "android" / "app" / "src" / "main" / "assets" / "www"

IMPORT_RE = re.compile(r"^import \{[^}]*\} from '[^']*';\s*$", re.M)
EXPORT_RE = re.compile(r"^export \{[^}]*\};\s*$", re.M)


def build_bundle() -> str:
    parts = []
    for name in ("data.js", "engine.js", "app.js"):
        text = (SRC / "js" / name).read_text(encoding="utf-8")
        text = IMPORT_RE.sub("", text)
        text = EXPORT_RE.sub("", text)
        parts.append(text)

    header = (
        "/* AI Lottery bundled for Android WebView (file:// compatible).\n"
        " * Generated by scripts/sync-web-assets.py from lottery-ai/js.\n"
        " * Edit the sources in lottery-ai/js, do not edit this file.\n"
        " */\n"
        "(function () {\n'use strict';\n\n"
    )
    return header + "\n".join(parts) + "\n})();\n"


def main() -> int:
    if not SRC.is_dir():
        print(f"missing source directory: {SRC}", file=sys.stderr)
        return 1

    (DST / "js").mkdir(parents=True, exist_ok=True)
    (DST / "css").mkdir(parents=True, exist_ok=True)

    html = (SRC / "index.html").read_text(encoding="utf-8")
    html = html.replace(
        '<script type="module" src="js/app.js"></script>',
        '<script src="js/bundle.js"></script>',
    )
    (DST / "index.html").write_text(html, encoding="utf-8")

    shutil.copyfile(SRC / "css" / "style.css", DST / "css" / "style.css")

    bundle = build_bundle()
    (DST / "js" / "bundle.js").write_text(bundle, encoding="utf-8")

    print(f"synced assets to {DST} ({len(bundle.encode('utf-8'))} bytes bundle)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
